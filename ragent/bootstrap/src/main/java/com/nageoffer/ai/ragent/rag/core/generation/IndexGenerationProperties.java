package com.nageoffer.ai.ragent.rag.core.generation;

import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import lombok.Data;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.context.annotation.Configuration;
import org.springframework.validation.annotation.Validated;

@Data
@Validated
@Configuration
@ConfigurationProperties(prefix = "rag.index-generation")
public class IndexGenerationProperties {
    /** Must stay disabled until upgrade_index_generation.sql has been applied. */
    private boolean enabled = false;

    @Min(1)
    @Max(168)
    private long rollbackRetentionHours = 24;
}
